/** Rebuild release attribution from the installed, locked production tree. */
import { execFileSync } from 'node:child_process';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const repo = resolve(import.meta.dirname, '../..');
interface Package {
  name: string;
  versions: string[];
  license: string;
  homepage?: string;
  paths: string[];
}
const packages = Object.values(
  JSON.parse(
    execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
      cwd: repo,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    }),
  ) as Record<string, Package[]>,
)
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name));
const sources = JSON.parse(
  await readFile(join(repo, 'legal/upstream/sources.json'), 'utf8'),
) as Record<string, { file: string; source: string }>;
const sections: string[] = [];
for (const pkg of packages) {
  const texts = new Set<string>();
  for (const path of pkg.paths) {
    for (const name of (await readdir(path)).sort()) {
      if (/^(licen[cs]e|copying|copyright|notice)([.-]|$)/iu.test(name))
        texts.add(
          (await readFile(join(path, name), 'utf8'))
            .replace(/\r\n?/gu, '\n')
            .trim(),
        );
    }
  }
  if (texts.size === 0) {
    for (const version of pkg.versions) {
      const source = sources[`${pkg.name}@${version}`];
      if (!source)
        throw new Error(
          `Missing license text: ${pkg.name}@${version}. Review upstream and add its versioned source.`,
        );
      texts.add(
        `${source.source}\n\n${(await readFile(join(repo, 'legal/upstream', source.file), 'utf8')).trim()}`,
      );
    }
  }
  sections.push(
    [
      `${pkg.name} ${pkg.versions.join(', ')}`,
      `License: ${pkg.license}`,
      ...(pkg.homepage ? [`Homepage: ${pkg.homepage}`] : []),
      '',
      ...texts,
    ].join('\n'),
  );
}
const text = [
  'Third-party notices for SimpleBot',
  '',
  'SimpleBot is licensed Apache-2.0 (see LICENSE).',
  'Production server and bundled frontend dependencies retain the notices below.',
  'Generated by pnpm legal:notices from the installed lockfile-resolved tree.',
  'Versioned sources for packages missing license files: legal/upstream/sources.json.',
  '',
  sections.join(`\n\n${'-'.repeat(72)}\n\n`),
  '',
]
  .join('\n')
  .replace(/[\t ]+$/gmu, '');
const output = join(repo, 'legal/THIRD-PARTY-NOTICES.txt');
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== text)
    throw new Error('Notices are stale. Run pnpm legal:notices.');
} else await writeFile(output, text);
console.log(`${String(packages.length)} production package notices verified.`);
